from datetime import date, datetime, timedelta, timezone
import os

import jwt
import psycopg
from fastapi import Depends, FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from pydantic import BaseModel, Field
from psycopg.rows import dict_row
from psycopg.errors import UniqueViolation
from pwdlib import PasswordHash

app = FastAPI()

# Set FRONTEND_ORIGIN in production to your deployed frontend URL.
# Local development continues to allow the two localhost origins.
frontend_origins = os.environ.get(
    "FRONTEND_ORIGIN",
    "http://127.0.0.1:5500,http://localhost:5500",
)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[origin.strip() for origin in frontend_origins.split(",") if origin.strip()],
    allow_credentials=False,
    allow_methods=["GET", "POST", "PUT", "DELETE", "OPTIONS"],
    allow_headers=["Authorization", "Content-Type"],
)

DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("Set the DATABASE_URL environment variable before starting the app.")

SECRET_KEY = os.environ.get("EXPENSES_SECRET_KEY")
if not SECRET_KEY:
    raise RuntimeError("Set the EXPENSES_SECRET_KEY environment variable before starting the app.")

password_hash = PasswordHash.recommended()
ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_MINUTES = 30
bearer_scheme = HTTPBearer()


def get_connection():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def initialize_database():
    # Neon is a new PostgreSQL database. These statements create the schema if needed.
    with get_connection() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS expenses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                description TEXT NOT NULL,
                category TEXT NOT NULL,
                amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
                expense_date DATE,
                user_id BIGINT REFERENCES users(id) ON DELETE CASCADE
            )
            """
        )


initialize_database()


def create_access_token(user_id: int):
    expires_at = datetime.now(timezone.utc) + timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
    payload = {"sub": str(user_id), "exp": expires_at}
    return jwt.encode(payload, SECRET_KEY, algorithm=ALGORITHM)


def get_current_user(
    credentials: HTTPAuthorizationCredentials = Depends(bearer_scheme),
):
    try:
        payload = jwt.decode(credentials.credentials, SECRET_KEY, algorithms=[ALGORITHM])
        user_id = int(payload["sub"])
    except (jwt.InvalidTokenError, KeyError, TypeError, ValueError):
        raise HTTPException(
            status_code=401,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        )

    with get_connection() as connection:
        user = connection.execute(
            "SELECT id, email FROM users WHERE id = %s", (user_id,)
        ).fetchone()

    if user is None:
        raise HTTPException(
            status_code=401,
            detail="User no longer exists",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return dict(user)


class ExpenseCreate(BaseModel):
    description: str = Field(min_length=1, max_length=100)
    category: str = Field(min_length=1, max_length=50)
    amount: float = Field(gt=0, le=1000000)
    expense_date: date


class UserCreate(BaseModel):
    email: str = Field(min_length=5, max_length=254)
    password: str = Field(min_length=8, max_length=128)


class UserLogin(BaseModel):
    email: str
    password: str


@app.get("/")
def home():
    return {"message": "Welcome to Expense Tracker API!"}


@app.get("/health")
def health():
    # Also confirms the app can reach PostgreSQL.
    with get_connection() as connection:
        connection.execute("SELECT 1").fetchone()
    return {"status": "ok", "database": "connected"}


@app.post("/api/register", status_code=201)
def register_user(user: UserCreate):
    email = user.email.strip().lower()
    if not email or "@" not in email:
        raise HTTPException(status_code=422, detail="Enter a valid email address")

    hashed_password = password_hash.hash(user.password)
    try:
        with get_connection() as connection:
            row = connection.execute(
                """
                INSERT INTO users (email, password_hash)
                VALUES (%s, %s)
                RETURNING id
                """,
                (email, hashed_password),
            ).fetchone()
            user_id = row["id"]
    except UniqueViolation:
        raise HTTPException(status_code=409, detail="An account with this email already exists")

    return {"message": "Account created successfully", "user_id": user_id, "email": email}


@app.post("/api/login")
def login_user(user: UserLogin):
    email = user.email.strip().lower()
    with get_connection() as connection:
        account = connection.execute(
            "SELECT id, email, password_hash FROM users WHERE email = %s", (email,)
        ).fetchone()

    if account is None or not password_hash.verify(user.password, account["password_hash"]):
        raise HTTPException(
            status_code=401,
            detail="Invalid email or password",
            headers={"WWW-Authenticate": "Bearer"},
        )

    return {
        "access_token": create_access_token(account["id"]),
        "token_type": "bearer",
        "user_id": account["id"],
        "email": account["email"],
    }


@app.get("/api/expenses")
def get_expenses(current_user: dict = Depends(get_current_user)):
    with get_connection() as connection:
        rows = connection.execute(
            """
            SELECT id, description, category, amount, expense_date
            FROM expenses
            WHERE user_id = %s
            ORDER BY id DESC
            """,
            (current_user["id"],),
        ).fetchall()
    return [dict(row) for row in rows]


@app.post("/api/expenses", status_code=201)
def create_expense(expense: ExpenseCreate, current_user: dict = Depends(get_current_user)):
    description = expense.description.strip()
    category = expense.category.strip()
    if not description or not category:
        raise HTTPException(status_code=422, detail="Description and category are blank")

    with get_connection() as connection:
        row = connection.execute(
            """
            INSERT INTO expenses (description, category, amount, expense_date, user_id)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id, description, category, amount, expense_date
            """,
            (description, category, expense.amount, expense.expense_date, current_user["id"]),
        ).fetchone()
    return dict(row)


@app.delete("/api/expenses/{expense_id}")
def delete_expense(expense_id: int, current_user: dict = Depends(get_current_user)):
    with get_connection() as connection:
        cursor = connection.execute(
            "DELETE FROM expenses WHERE id = %s AND user_id = %s",
            (expense_id, current_user["id"]),
        )
        if cursor.rowcount == 0:
            raise HTTPException(status_code=404, detail="Expense not found")
    return {"message": "Expense deleted successfully"}


@app.put("/api/expenses/{expense_id}")
def update_expense(
    expense_id: int,
    expense: ExpenseCreate,
    current_user: dict = Depends(get_current_user),
):
    description = expense.description.strip()
    category = expense.category.strip()
    if not description or not category:
        raise HTTPException(status_code=422, detail="Description and category are blank")

    with get_connection() as connection:
        cursor = connection.execute(
            """
            UPDATE expenses
            SET description = %s, category = %s, amount = %s, expense_date = %s
            WHERE id = %s AND user_id = %s
            """,
            (
                description,
                category,
                expense.amount,
                expense.expense_date,
                expense_id,
                current_user["id"],
            ),
        )
        if cursor.rowcount == 0:
            raise HTTPException(status_code=404, detail="Expense not found")
        row = connection.execute(
            """
            SELECT id, description, category, amount, expense_date
            FROM expenses WHERE id = %s AND user_id = %s
            """,
            (expense_id, current_user["id"]),
        ).fetchone()
    return dict(row)
